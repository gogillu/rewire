# harvest-posters.ps1 — v1.6.2
#
# Reads audit-posters.json (produced by audit-posters.ps1), and for
# every movie with status BROKEN tries multiple Wikipedia title
# variants until it finds a summary endpoint that returns a real
# `originalimage.source` URL that resolves to image/*.
#
# Outputs:
#   poster-fixes.txt   — human-readable mapping (id => url, or FAILED)
#   poster-fixes.go    — Go map literal ready to paste into
#                         poster_overrides.go
#   poster-manual.txt  — one line per movie that we could not auto-fix
#
# Conservative: 250ms between requests, polite UA, max 6 variants per
# movie.

[CmdletBinding()]
param(
    [string]$InDir  = 'C:\Users\arushi\.copilot\session-state\abd0700f-1772-4351-81ba-707e1cdfc3db\files\rewire-runtime',
    [string]$OutDir = 'C:\Users\arushi\.copilot\session-state\abd0700f-1772-4351-81ba-707e1cdfc3db\files\rewire-runtime'
)
$ErrorActionPreference = 'Stop'

$ua = @{ 'User-Agent' = 'rewire-poster-audit/1.0 (https://gogillu.in; admin@gogillu.in)' }
$auditPath = Join-Path $InDir 'audit-posters.json'
if (-not (Test-Path $auditPath)) { throw "audit-posters.json missing — run audit-posters.ps1 first" }
$audit = Get-Content $auditPath -Raw | ConvertFrom-Json
$broken = @($audit | Where-Object { $_.status -ne 'OK' })
Write-Host "Broken movies to fix: $($broken.Count)" -ForegroundColor Cyan

function Get-WikiSummary($title) {
    try {
        $enc = [uri]::EscapeUriString($title)
        $r = Invoke-WebRequest -Uri "https://en.wikipedia.org/api/rest_v1/page/summary/$enc" -Headers $ua -UseBasicParsing -TimeoutSec 8
        return $r.Content | ConvertFrom-Json
    } catch { return $null }
}

function Test-ImageUrl($url) {
    if ([string]::IsNullOrWhiteSpace($url)) { return $false }
    try {
        $h = Invoke-WebRequest -Uri $url -Method Head -UseBasicParsing -TimeoutSec 8 -MaximumRedirection 5 -Headers $ua
        return ($h.StatusCode -eq 200 -and "$($h.Headers.'Content-Type')" -match '^image/')
    } catch { return $false }
}

function Get-Variants($m) {
    $t = $m.title
    $y = [int]$m.year
    $kind = $m.kind
    $region = $m.region
    $variants = New-Object System.Collections.Generic.List[string]
    if ($kind -eq 'tv') {
        if ($y -gt 0) { $variants.Add("$t ($y TV series)") }
        switch ($region) {
            'bollywood' { $variants.Add("$t (Indian TV series)"); $variants.Add("$t (Hindi TV series)"); $variants.Add("$t (web series)"); $variants.Add("$t (Indian web series)") }
            'hollywood' { $variants.Add("$t (American TV series)"); $variants.Add("$t (British TV series)") }
            'world'     { $variants.Add("$t (South Korean TV series)"); $variants.Add("$t (German TV series)"); $variants.Add("$t (Spanish TV series)") }
        }
    } else {
        if ($y -gt 0) { $variants.Add("$t ($y film)") }
        switch ($region) {
            'bollywood' { $variants.Add("$t (Hindi film)"); $variants.Add("$t (Indian film)") }
            'hollywood' { $variants.Add("$t (American film)") }
        }
        $variants.Add("$t (film)")
    }
    $variants.Add($t)
    return $variants | Select-Object -Unique
}

$fixes  = @{}
$manual = @()
$i = 0
foreach ($m in $broken) {
    $i++
    $variants = Get-Variants -m $m
    $found = $null
    $tried = @()
    foreach ($v in $variants) {
        $tried += $v
        $sum = Get-WikiSummary $v
        if (-not $sum) { Start-Sleep -Milliseconds 200; continue }
        $candidate = $sum.originalimage.source
        if (-not $candidate) { $candidate = $sum.thumbnail.source }
        if (-not $candidate) { Start-Sleep -Milliseconds 200; continue }
        if (Test-ImageUrl $candidate) {
            $found = $candidate
            break
        }
        Start-Sleep -Milliseconds 200
    }
    if ($found) {
        Write-Host ("[{0,3}/{1}] FIXED   {2,-32} -> {3}" -f $i, $broken.Count, $m.id, $found) -ForegroundColor Green
        $fixes[$m.id] = $found
    } else {
        Write-Host ("[{0,3}/{1}] FAILED  {2,-32} (tried: {3})" -f $i, $broken.Count, $m.id, ($tried -join ' | ')) -ForegroundColor Red
        $manual += [PSCustomObject]@{
            id    = $m.id
            title = $m.title
            year  = $m.year
            tried = ($tried -join ' | ')
        }
    }
}

$txt = $fixes.GetEnumerator() | Sort-Object Key | ForEach-Object { "$($_.Key) => $($_.Value)" }
$txt | Set-Content -Path (Join-Path $OutDir 'poster-fixes.txt') -Encoding UTF8

$go = New-Object System.Collections.Generic.List[string]
$go.Add("// Auto-generated by harvest-posters.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss').")
$go.Add("// Paste these into the posterOverrides map in poster_overrides.go.")
foreach ($k in ($fixes.Keys | Sort-Object)) {
    $key = '"' + $k + '":'
    $val = '"' + $fixes[$k] + '",'
    $go.Add(("`t{0,-30} {1}" -f $key, $val))
}
$go | Set-Content -Path (Join-Path $OutDir 'poster-fixes.go') -Encoding UTF8

$manual | ForEach-Object { "{0} :: {1} ({2}) :: tried {3}" -f $_.id, $_.title, $_.year, $_.tried } |
    Set-Content -Path (Join-Path $OutDir 'poster-manual.txt') -Encoding UTF8

Write-Host ""
Write-Host "==== Summary ====" -ForegroundColor Yellow
Write-Host "  fixed  : $($fixes.Count)"
Write-Host "  manual : $($manual.Count)"
Write-Host "  out    : $OutDir\poster-fixes.{txt,go}, poster-manual.txt"
